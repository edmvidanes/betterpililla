import { expect, test } from '@playwright/test'

test('main services links to the district and assistance while municipal records stay withheld', async ({ page, request }) => {
  await page.goto('/en/services')
  await expect(page.locator('main a[href="/en/services/water-district"]')).toBeVisible()
  await expect(page.locator('main a[href="/en/services/public-contacts"]')).toBeVisible()
  await expect(page.locator('main')).toContainText('Municipal services · WorkInProgress')
  const data = await (await request.get('/data/services.json')).json()
  expect(data.services).toEqual([])
  await page.locator('main a[href="/en/services/water-district"]').click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Pililla Water District')
  await expect(page.locator('#services .provider-review')).toHaveCount(13)
  await expect(page.locator('#rates')).toContainText('₱300.65')
  await page.getByRole('combobox').selectOption('2')
  await expect(page.locator('#rates')).toContainText('₱6,012.90')
  await expect(page.locator('#rates')).not.toContainText('₱300.65')
  await expect(page.locator('[data-external-url="https://forms.gle/JnXpRmUmLsUMfvDN6"]')).toContainText('WorkInProgress')
  await expect(page.locator('a[href="https://forms.gle/JnXpRmUmLsUMfvDN6"]')).toHaveCount(0)
  await expect(page.locator('#services a[href$="WAIVER-TRANSFER-OF-RIGHT.bmp"]')).toHaveCount(1)
  await expect(page.locator('#services')).toContainText('Contract Agreement Form — WorkInProgress')
})
