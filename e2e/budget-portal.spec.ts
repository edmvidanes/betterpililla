import { expect, test } from '@playwright/test'

test('Transparency dropdown opens same-site budget records and exports', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/en/transparency')
  const menu = page.locator('.nav-group').filter({ has: page.locator('summary', { hasText: 'Transparency' }) })
  await menu.locator('summary').click()
  await menu.getByRole('link', { name: 'Budget projects · FY2027', exact: true }).click()
  await expect(page).toHaveURL(/:4174\/en\/transparency\/budget$/)
  const budget = page.frameLocator('.budget-portal-frame')
  await expect(budget.getByRole('heading', { level: 1 })).toContainText('5 source projects')
  await expect(budget.getByRole('button', { name: 'Download CSV', exact: true })).toBeVisible()
  const download = page.waitForEvent('download')
  await budget.getByRole('button', { name: 'Download CSV', exact: true }).click()
  expect((await download).suggestedFilename()).toBe('pililla-rizal-fy2027-projects.csv')
  await budget.getByRole('link', { name: 'Budgets 2020–2026', exact: true }).click()
  await expect(page).toHaveURL(/\/en\/transparency\/budget\/gaa$/)
  await expect(budget.getByRole('heading', { level: 1 })).toContainText('37 programs and projects')
  await budget.getByRole('link', { name: '2027 projects', exact: true }).click()
  await budget.getByRole('link', { name: /Sagbat-Pililla Div Rd/ }).first().click()
  await expect(page).toHaveURL(/\/en\/transparency\/budget\/projects\/dpwh\//)
  await expect(budget.getByRole('heading', { level: 1 })).toContainText('Pililla')
  await page.reload()
  await expect(budget.getByRole('heading', { level: 1 })).toContainText('Pililla')
  await page.getByRole('link', { name: 'Filipino', exact: true }).click()
  await expect(page).toHaveURL(/\/fil\/transparency\/budget\/projects\/dpwh\//)
  await expect(budget.getByRole('heading', { level: 1 })).toContainText('Pililla')
  expect(errors).toEqual([])
})

test('integrated budgets work on mobile without the separate portal server', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.route('http://127.0.0.1:5132/**', route => route.abort())
  await page.goto('/fil/transparency/budget/gaa')
  const budget = page.frameLocator('.budget-portal-frame')
  await expect(budget.getByRole('heading', { level: 1 })).toContainText('37 programs and projects')
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Mga naisabatas na badyet · 2020–2026')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  const frame = page.frames().find(frame => frame.url().includes('/budget-portal/'))!
  expect(new URL(frame.url()).port).toBe('4174')
  expect(await frame.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await expect.poll(async () => Number(await page.locator('iframe').getAttribute('height'))).toBeGreaterThan(1000)
})
